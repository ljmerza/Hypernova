test('masking time grows with the line, not faster: four times the text, about four times the time', () => {
  // The slowest shapes found: a quadratic rule would take 16 times as long on the longer line.
  for (const unit of ['TOKEN-', 'Authorization: Bearer ', 'a-', '://a:', 'TOKEN="a1']) {
    const time = (n: number) => {
      const s = unit.repeat(n)
      let best = Infinity
      for (let i = 0; i < 3; i++) {
        const t0 = performance.now()
        maskSecrets(s)
        best = Math.min(best, performance.now() - t0)
      }
      return best
    }
    const short = time(4_000)
    const long = time(16_000)
    assert.ok(long < Math.max(short, 1) * 9, `${unit}: ${short.toFixed(1)} ms, then ${long.toFixed(1)} ms`)
  }
})

