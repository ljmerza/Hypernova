test('typed into a shared terminal while Claude works: prompts and "!" lines are queued, slash commands not, and a send not queued is forgotten', async () => {
  const { createServer } = await import('node:net')
  const { Frames, MSG, msg, metaPath, sockPath } = await import('../src/term/shared.ts')
  const { scanTerms, typeInto } = await import('../src/terms.ts')
  const { claimPaste, claimRewritten } = await import('../src/hub.ts')
  const tid = 'fa4e0001aa'
  // A holder that says Claude Code queued every prompt but one (Claude was busy).
  let hello = () => {}
  const ready = new Promise<void>((r) => (hello = r))
  const conns = new Set<import('node:net').Socket>()
  const server = createServer((s) => {
    conns.add(s)
    const frames = new Frames((type, p) => {
      if (type !== MSG) return
      const m = JSON.parse(p.toString('utf8'))
      if (m.t === 'hello') {
        s.write(msg({ t: 'hello', v: 1, id: tid, caps: ['replace', 'mode', 'queued'], cols: 100, rows: 34, title: '', childPid: null, tty: 0, phone: 0, started: true }))
        hello()
      } else if (m.t === 'paste') s.write(msg({ t: 'pasted', id: m.id, ok: true, queued: m.text !== 'started a turn' }))
    })
    s.on('data', (b: Buffer) => frames.push(b))
  })
  await new Promise<void>((r) => server.listen(sockPath(tid), r))
  writeFileSync(metaPath(tid), JSON.stringify({ v: 1, id: tid, pid: process.pid, childPid: null, cwd: '/tmp/holder', args: [], origin: 'hypernova', sessionId: null, createdAt: Date.now(), terminal: { app: null }, title: '', tty: 0, phone: 0 }))
  try {
    scanTerms()
    await ready
    const send = async (text: string, clientId: string) => (await typeInto(tid, text, false, clientId)).queued
    // /cost opens its panel at once, even while Claude works.
    assert.equal(await send('/cost', 'cmd-1'), false)
    assert.equal(await send('!echo hi-from-bash', 'bash-1'), true)
    assert.equal(await send('and the tests', 'p-1'), true)
    assert.equal(await send('started a turn', 'p-2'), false)
    assert.equal(claimPaste(tid, '/cost'), null)
    assert.equal(claimPaste(tid, 'started a turn'), null)
    assert.deepEqual(claimPaste(tid, 'echo hi-from-bash'), { clientId: 'bash-1', bash: true, text: '!echo hi-from-bash' })
    // A queued send stays claimable a few seconds after the holder answered, and no longer.
    const realNow = Date.now
    Date.now = () => realNow() + 6000
    try {
      assert.equal(claimPaste(tid, 'and the tests'), null)
    } finally {
      Date.now = realNow
    }
    assert.deepEqual(claimPaste(tid, 'and the tests'), { clientId: 'p-1', bash: false, text: 'and the tests' })
    // The prompt that started a turn waits for its own entry, should a hook rewrite it; no command does.
    assert.deepEqual(claimRewritten(tid, Date.now()), { clientId: 'p-2', bash: false, text: 'started a turn' })
    assert.equal(claimRewritten(tid, Date.now()), null)
  } finally {
    for (const s of conns) s.destroy()
    await new Promise<void>((r) => server.close(() => r()))
    rmSync(metaPath(tid), { force: true })
    rmSync(sockPath(tid), { force: true })
    scanTerms()
  }
})

