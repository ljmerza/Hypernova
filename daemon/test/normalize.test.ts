test('a command that turns out to be a skill is sent to the phone again', async () => {
  const { addClient, upsertSession, ensureParsed, pollTranscripts } = await import('../src/hub.ts')
  const dir = join(process.env.CLAUDE_CONFIG_DIR!, 'projects', '-tmp-live')
  mkdirSync(dir, { recursive: true })
  const id = 'bbbbbbbb-0000-4000-8000-000000000001'
  const path = join(dir, `${id}.jsonl`)
  const line = (e: object) => JSON.stringify(e) + '\n'
  writeFileSync(path, line(user('r1', null, skill('/hyper-cosmos', 'make a page'))))
  const r = upsertSession(id, { cwd: '/tmp/live', transcriptPath: path, state: 'working' })
  ensureParsed(r)
  const sent: any[] = []
  const remove = addClient({ send: (s) => sent.push(JSON.parse(s)) })
  try {
    appendFileSync(path, line(user('b1', 'r1', [{ type: 'text', text: 'Base directory for this skill: /tmp/hc\n\nBody.' }], { isMeta: true })))
    pollTranscripts()
    const ev = sent.find((m) => m.t === 'event' && m.sessionId === id && m.event.id === 'r1')
    assert.ok(ev, 'the command event was sent again')
    assert.deepEqual(ev.event.command, { name: '/hyper-cosmos', args: 'make a page', kind: 'skill' })
    // Nothing is sent again on the next look.
    sent.length = 0
    pollTranscripts()
    assert.equal(sent.filter((m) => m.t === 'event' && m.sessionId === id).length, 0)
  } finally {
    remove()
  }
})

