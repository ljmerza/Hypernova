test('a skill body marks only the command it follows, and says the command changed', () => {
  const st = parse(user('r1', null, skill('/telegram:access')), user('u1', 'r1', 'and then this'))
  assert.deepEqual([...st.changed], [])
  // The model loading a skill through its tool: the body comes from a tool use, under a prompt.
  feedLine(st, user('b0', 'u1', [{ type: 'text', text: 'Base directory for this skill: /tmp/x' }], { isMeta: true, sourceToolUseID: 'toolu_1' }))
  // A body under a plain prompt, and under nothing known.
  feedLine(st, user('b1', 'u1', [{ type: 'text', text: 'Base directory for this skill: /tmp/x' }], { isMeta: true }))
  feedLine(st, user('b2', 'nope', [{ type: 'text', text: 'Base directory for this skill: /tmp/x' }], { isMeta: true }))
  assert.deepEqual([...st.changed], [])
  assert.deepEqual(shape(st.events)[1], { id: 'u1', kind: 'user', text: 'and then this' })
  feedLine(st, user('b3', 'r1', [{ type: 'text', text: 'Base directory for this skill: /tmp/access' }], { isMeta: true }))
  assert.deepEqual([...st.changed], ['r1'])
  const ev = st.byId.get('r1')!
  assert.equal(ev.kind === 'user' && ev.command?.kind, 'skill')
  // The same event object is in the list the phone gets.
  assert.equal(st.events[0], ev)
})

