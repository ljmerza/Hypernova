// ── Fixture helpers ──────────────────────────────────────────────────────
const T0 = Date.parse('2026-10-14T10:00:00.000Z')
let tick = 0
const at = () => new Date(T0 + tick++ * 1000).toISOString()
const base = (uuid: string, parentUuid: string | null) => ({ uuid, parentUuid, timestamp: at(), sessionId: 'sess-1', cwd: '/tmp/demo', isSidechain: false })
const user = (uuid: string, parentUuid: string | null, content: unknown, extra: object = {}) => ({ ...base(uuid, parentUuid), type: 'user', message: { role: 'user', content }, ...extra })
const system = (uuid: string, parentUuid: string | null, subtype: string, content: string, extra: object = {}) => ({ ...base(uuid, parentUuid), type: 'system', subtype, content, level: 'info', isMeta: false, ...extra })
const assistant = (uuid: string, parentUuid: string | null, text: string) => ({ ...base(uuid, parentUuid), type: 'assistant', message: { id: `msg-${uuid}`, role: 'assistant', model: 'claude-test', content: [{ type: 'text', text }] } })
const parse = (...entries: object[]) => parseTranscript(entries.map((e) => JSON.stringify(e)).join('\n'))

/** Built-in command record: name, message, args, joined by a newline and 12 spaces. */
const builtIn = (name: string, args = '') => {
  const gap = '\n            '
  return `<command-name>${name}</command-name>${gap}<command-message>${name.slice(1)}</command-message>${gap}<command-args>${args}</command-args>`
}
/** Skill or prompt command record: message first, no indent, no args line without args. */
const skill = (name: string, args?: string) =>
  `<command-message>${name.slice(1)}</command-message>\n<command-name>${name}</command-name>${args ? `\n<command-args>${args}</command-args>` : ''}`
const CAVEAT = '<local-command-caveat>The command below was run directly in Claude Code, not by the model. Do not respond to it unless asked.</local-command-caveat>'
const OLD_CAVEAT =
  '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>'

/** Events without timestamps, for comparing. */
const shape = (events: Ev[]) => events.map(({ ts: _ts, ...e }) => e)

// ── Built-in commands ────────────────────────────────────────────────────
test('built-in command, user form: caveat, record, output', () => {
  const st = parse(
    user('c1', null, CAVEAT, { isMeta: true }),
    user('r1', 'c1', builtIn('/effort', 'ultracode')),
    user('o1', 'r1', '<local-command-stdout>Ultracode on (this session only): dynamic workflows on every task. Effort stays xhigh.</local-command-stdout>'),
  )
  assert.deepEqual(shape(st.events), [
    { id: 'r1', kind: 'user', text: '/effort ultracode', command: { name: '/effort', args: 'ultracode', kind: 'local' } },
    { id: 'o1', kind: 'notice', text: 'Ultracode on (this session only): dynamic workflows on every task. Effort stays xhigh.', tone: 'info', command: 'r1' },
  ])
})

