const plain = (group: string, more: Partial<Entry> = {}): Entry => ({ group, take: 'plain', ...more })
const runs = (group: string, more: Partial<Entry> = {}): Entry => ({ group, take: 'runs', ...more })
const loosens = (group: string, more: Partial<Entry> = {}): Entry => ({ group, take: 'loosens', ...more })
const reach = (group: string, more: Partial<Entry> = {}): Entry => ({ group, take: 'reach', ...more })
const managed: Entry = { group: 'managed', take: 'unknown', managed: true }
const screen = (group: string, s: Screen): Entry => ({ group, take: 'unknown', screen: s })

