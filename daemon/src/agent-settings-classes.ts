// What each of the agents' settings takes in the form (docs/DECISIONS.md, "Every setting, from the agents' own schemas"; the
// risk: docs/SECURITY-MODEL.md, 25). One reviewed table per agent, every key of the shipped schema in it:
// test/agent-settings-form.test.ts fails on a key that isn't, so a refreshed schema can't bring one in unlooked at. A key this
// has never heard of, in a file from a later agent, asks ([UNKNOWN]): it never slips through as plain.
//
// - plain: changes what's shown or how much is kept, not what can act. Saved with no question.
// - runs: can make a command run on the server.
// - loosens: lets the agent do more without asking, or takes a guard off.
// - reach: changes what's allowed, who can sign in, or where data and files go.
// - unknown: not known well enough to call plain.
//
// Those last four take a plain one-tap confirm, and the server wants the flag that says it was given. The owner chose that over
// the fingerprint here ("don't add fingerprinting needed"); the JSON tab and everything else keep theirs.
//
// - managed: does nothing outside a managed install. Hidden; read-only if the file has it, and refused on the server.
// - screen: has its own screen, so the form points there and the server refuses it here.
// - refuse: a value that switches a check off for good. Can only be taken out.
// - mask: a command's text that stays on the server as a whole, whatever it looks like.
// - notRead: Claude Code 2.1.318's own settings check has no such key. See docs/DECISIONS.md for how that was measured.

export type Take = 'plain' | 'runs' | 'loosens' | 'reach' | 'unknown'
export type Screen = 'rules' | 'mcp' | 'plugins' | 'env' | 'effort'
export type Applies = 'new_sessions' | 'maybe_new_session' | 'next_update' | 'new_threads' | 'new_threads_unchosen'
export type Entry = { group: string; take: Take; managed?: true; screen?: Screen; refuse?: true; mask?: true; notRead?: true; applies?: Applies }

export const UNKNOWN: Entry = { group: 'other', take: 'unknown' }

