// Measures the advance of every glyph the drawn look may need in the two bundled fonts (Manrope at
// the weights it uses, JetBrains Mono) and writes src/core/type-table.ts, so text can be laid out
// the same way in the WebView and under node (tests). Run from lens/: `node dev/type-metrics.mjs`.
// Headless Chromium (Playwright) does the measuring: the advances come from the font files, which
// the Even App's WebView reads the same way. A glyph a font lacks is left out (it would fall back to
// a system font of unknown width), found by measuring it over two very different fallbacks.
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('..', import.meta.url);
const font = f => readFileSync(new URL(`src/phone/fonts/${f}`, here)).toString('base64');

const ranges = [[0x20, 0x7e], [0xa0, 0xff], [0x400, 0x45f], [0x490, 0x491]];
const extra = '‐‑‒–—―‘’‚“”„†‡•…‰′″‹›⁄€№™←↑→↓↔↕⇐⇒✓✗▶▸▾●○■□─━│⏺▁▂▃▄▅▆▇█≈≠≤≥−×÷';
const chars = [...new Set([...ranges.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i))), ...extra])];
const WEIGHTS = [300, 500, 600, 700];

const browser = await chromium.launch();
const page = await browser.newPage();
const out = await page.evaluate(async ({ manrope, mono, chars, weights }) => {
  const load = async (family, b64) => {
    const bytes = Uint8Array.from(atob(b64), c => c.charCodeAt(0));
    const f = new FontFace(family, bytes, { weight: '100 900' });
    await f.load();
    document.fonts.add(f);
  };
  await load('M', manrope);
  await load('J', mono);
  const c = document.createElement('canvas').getContext('2d');
  c.fontKerning = 'none';
  const at = (family, w, ch) => { c.font = `${w} 1000px ${family}`; return c.measureText(ch).width; };
  const has = (family, w, ch) => ch === ' ' || ch === ' ' || Math.abs(at(`${family}, "Courier New"`, w, ch) - at(`${family}, "Times New Roman"`, w, ch)) < 0.5;
  const table = (family, w) => {
    const keep = chars.filter(ch => has(family, w, ch));
    return { chars: keep.join(''), widths: keep.map(ch => Math.round(at(family, w, ch) * 10) / 10) };
  };
  return { sans: Object.fromEntries(weights.map(w => [w, table('M', w)])), mono: table('J', 500) };
}, { manrope: font('Manrope.ttf'), mono: font('JetBrainsMono.ttf'), chars, weights: WEIGHTS });
await browser.close();

const lines = [
  '// Generated by dev/type-metrics.mjs from src/phone/fonts (Manrope, JetBrains Mono; SIL OFL 1.1, see',
  '// public/fonts): each glyph\'s advance in thousandths of an em, without kerning. Do not edit by hand.',
  '',
  '/** Manrope by weight: the glyphs it has (a string) and their advances, in order. */',
  'export const SANS: Record<number, { chars: string; widths: number[] }> = {',
  ...WEIGHTS.map(w => `  ${w}: { chars: ${JSON.stringify(out.sans[w].chars)}, widths: [${out.sans[w].widths.join(',')}] },`),
  '};',
  '',
  '/** JetBrains Mono (one weight: a monospace font\'s advances don\'t change with it): its glyphs and their advances. */',
  `export const MONO = { chars: ${JSON.stringify(out.mono.chars)}, widths: [${out.mono.widths.join(',')}] };`,
  '',
];
writeFileSync(new URL('src/core/type-table.ts', here), lines.join('\n'));
console.log('sans', WEIGHTS.map(w => `${w}:${out.sans[w].chars.length}`).join(' '), 'mono', out.mono.chars.length, 'advances', [...new Set(out.mono.widths)].join(','));
console.log('missing in Manrope 500:', chars.filter(ch => !out.sans[500].chars.includes(ch)).join(''));
console.log('missing in Mono:', chars.filter(ch => !out.mono.chars.includes(ch)).join(''));
